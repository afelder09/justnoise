#!/usr/bin/env bash
# Reads credentials from the running local Supabase stack and writes .env.test.local.
# When running in GitHub Actions (GITHUB_ENV is set), also exports to the workflow env.
# Called automatically by `npm run db:start`.
set -euo pipefail

STATUS=$(supabase status --output env 2>&1) || {
  echo "Error: could not read Supabase status. Is 'supabase start' running?"
  exit 1
}

extract() {
  echo "$STATUS" | grep "^$1=" | sed "s/^$1=\"//;s/\"$//"
}

SUPABASE_URL=$(extract API_URL)
ANON_KEY=$(extract ANON_KEY)
SERVICE_ROLE_KEY=$(extract SERVICE_ROLE_KEY)

cat > .env.test.local << EOF
# Generated by scripts/gen-test-env.sh — do not edit by hand.
# Recreate with: npm run db:start
NEXT_PUBLIC_SUPABASE_URL=${SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}
SPOTIFY_CLIENT_ID=test_placeholder
SPOTIFY_CLIENT_SECRET=test_placeholder
NEXT_PUBLIC_APP_URL=http://localhost:3000
EOF

echo "✓ .env.test.local written with local Supabase credentials"

# In GitHub Actions, also write to GITHUB_ENV so subsequent steps can reference
# the values as ${{ env.* }} without needing to source the file.
if [ -n "${GITHUB_ENV:-}" ]; then
  echo "NEXT_PUBLIC_SUPABASE_URL=${SUPABASE_URL}" >> "$GITHUB_ENV"
  echo "NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_KEY}" >> "$GITHUB_ENV"
  echo "SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}" >> "$GITHUB_ENV"
  echo "✓ Credentials exported to GITHUB_ENV"
fi
